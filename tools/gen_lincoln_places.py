#!/usr/bin/env python3
"""Turns tools/lincoln_places.tsv (category<TAB>NAME, researched from public Lincoln, NE business listings)
into core/.../categorize/LincolnPlaces.kt. Re-run after editing the TSV."""
import collections, os, re

here = os.path.dirname(os.path.abspath(__file__))
rows = [l.rstrip("\n").split("\t") for l in open(os.path.join(here, "lincoln_places.tsv")) if l.strip()]
valid = {"groceries", "eating_out", "gas_fuel", "shopping", "hobbies_art", "health", "personal_care", "entertainment",
         "transportation", "utilities", "phone_internet", "rent_housing", "pets", "travel", "gifts_donations",
         "insurance", "subscriptions", "other"}
by = collections.OrderedDict()
for cat, name in rows:
    assert cat in valid, cat
    assert re.fullmatch(r"[A-Z0-9&]+( [A-Z0-9&]+)*", name), name
    by.setdefault(cat, []).append(name)

out = ['package com.emotionalleaves.sprout.domain.categorize', '',
       '/**',
       ' * About 2,000 Lincoln, Nebraska businesses by category, researched from public business listings',
       ' * (generated by tools/gen_lincoln_places.py from tools/lincoln_places.tsv; edit those, not this file).',
       ' * Stored as one "|"-joined string per category to keep the class file small.',
       ' */',
       'internal object LincolnPlaces {',
       '    val places: List<Pair<String, List<String>>> by lazy {',
       '        listOf(']
for cat, names in by.items():
    joined = "|".join(names)
    assert len(joined.encode()) < 60000
    out.append(f'            "{cat}" to "{joined}",')
out += ['        ).map { (k, v) -> k to v.split(\'|\') }', '    }', '}', '']
dst = os.path.join(here, "..", "core/src/main/kotlin/com/emotionalleaves/sprout/domain/categorize/LincolnPlaces.kt")
open(dst, "w").write("\n".join(out))
print(sum(len(v) for v in by.values()), "places written")
